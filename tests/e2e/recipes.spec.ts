test('T01: Chromiumプロセスの再起動でもデータを保持', async ({ browserName, baseURL }, testInfo) => {
  test.skip(browserName !== 'chromium')
  const profile = await mkdtemp(join(tmpdir(), 'recipe-test-profile-'))
  const options = { ...testInfo.project.use.launchOptions, headless: true, viewport: { width: 390, height: 844 } }
  let context = await chromium.launchPersistentContext(profile, options)
  try {
    let page = await context.newPage(); await page.goto(`${baseURL}#/recipes/new`)
    await page.getByLabel('料理名').fill('再起動テストの架空料理')
    await page.getByRole('button', { name: '保存する' }).click()
    await expect(page.getByRole('heading', { name: '再起動テストの架空料理', exact: true })).toBeVisible()
    const url = page.url(); await context.close()
    context = await chromium.launchPersistentContext(profile, options)
    page = await context.newPage(); await page.goto(url)
    await expect(page.getByRole('heading', { name: '再起動テストの架空料理', exact: true })).toBeVisible()
  } finally { await context.close(); await rm(profile, { recursive: true, force: true }) }
})
