test('T13: IndexedDB書込み失敗で入力と既存データを保持', async ({ page }) => {
  await add(page)
  await page.getByRole('link', { name: 'レシピを編集' }).click()
  await page.getByLabel('料理名').fill('保存に失敗する名前')
  await page.evaluate(() => {
    Reflect.set(window, 'testOriginalPut', IDBObjectStore.prototype.put)
    const original = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args) { if (this.name === 'meta') throw new DOMException('injected', 'QuotaExceededError'); return original.apply(this, args) }
  })
  await page.getByRole('button', { name: '保存する' }).click()
  await expect(page.getByRole('alert')).toContainText('保存領域が足りません')
  await expect(page.getByLabel('料理名')).toHaveValue('保存に失敗する名前')
  await expect(page.getByText('レシピを保存しました。')).toHaveCount(0)
  await page.evaluate(() => { IDBObjectStore.prototype.put = Reflect.get(window, 'testOriginalPut') as IDBObjectStore['put'] })
  await page.getByRole('button', { name: 'キャンセル', exact: true }).click()
  await page.getByRole('button', { name: '破棄して戻る' }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: '架空の人参スープ', exact: true })).toBeVisible()
})
